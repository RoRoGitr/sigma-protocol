def all_slugs(wave: int | None = None):
    slugs = []
    max_wave = wave or 4
    for w in range(1, max_wave + 1):
        slugs.extend(WAVES[w]["orchestrators"])
        for row in all_step_rows():
            if row[3] in WAVES[w]["depts"]:
                slugs.append(row[0])
    return slugs
