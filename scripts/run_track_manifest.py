def prd_id_for_step(step_id: str) -> str:
    if step_id.startswith("Co"):
        num = int(step_id[2:])
        return f"Co{num:02d}.001"
    if step_id.startswith("Fn"):
        num = int(step_id[2:])
        return f"Fn{num:02d}.001"
    prefix = step_id[0]
    num = int(step_id[1:])
    return f"{prefix}{num:02d}.001"


